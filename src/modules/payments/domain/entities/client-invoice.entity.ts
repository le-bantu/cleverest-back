import { AbstractAggregateRoot, StoredFileRef } from '@shared/kernel';
import { ClientInvoiceAlreadyExists, paymentNotValidated } from '../errors';
import { ClientInvoiceGenerated, ClientInvoiceSent } from '../events/payment.events';
import { InvoiceNumber } from '../value-objects/invoice-number.vo';
import { Payment } from './payment.entity';

export interface ClientInvoiceProps {
  id: string;
  paymentId: string;
  missionId: string;
  clientId: string;
  invoiceNumber: InvoiceNumber;
  amount: number;
  pdfFile: StoredFileRef;
  generatedAt: Date;
  generatedById: string | null;
  sentAt: Date | null;
}

/** Invoice Cleverest issues to the client for a validated payment (PDF generated by the platform). */
export class ClientInvoice extends AbstractAggregateRoot<string> {
  private props: ClientInvoiceProps;

  private constructor(props: ClientInvoiceProps) {
    super(props.id);
    this.props = props;
  }

  /**
   * @param alreadyExists whether an invoice is stored for this payment
   */
  static generateFrom(
    input: {
      id: string;
      payment: Payment;
      invoiceNumber: InvoiceNumber;
      pdfFile: StoredFileRef;
      generatedById: string;
      alreadyExists: boolean;
    },
    now: Date,
  ): ClientInvoice {
    const { payment } = input;
    if (!payment.isValidated) throw paymentNotValidated(payment.id);
    if (input.alreadyExists) throw new ClientInvoiceAlreadyExists(payment.id);
    const invoice = new ClientInvoice({
      id: input.id,
      paymentId: payment.id,
      missionId: payment.missionId,
      clientId: payment.clientId,
      invoiceNumber: input.invoiceNumber,
      amount: payment.amount,
      pdfFile: input.pdfFile,
      generatedAt: now,
      generatedById: input.generatedById,
      sentAt: null,
    });
    invoice.addDomainEvent(
      new ClientInvoiceGenerated(
        input.id,
        {
          paymentId: payment.id,
          invoiceNumber: input.invoiceNumber.value,
          amount: payment.amount,
          actorId: input.generatedById,
        },
        now,
      ),
    );
    return invoice;
  }

  static rehydrate(props: ClientInvoiceProps): ClientInvoice {
    return new ClientInvoice({ ...props });
  }

  get paymentId(): string {
    return this.props.paymentId;
  }
  get missionId(): string {
    return this.props.missionId;
  }
  get clientId(): string {
    return this.props.clientId;
  }
  get invoiceNumber(): InvoiceNumber {
    return this.props.invoiceNumber;
  }
  get amount(): number {
    return this.props.amount;
  }
  get pdfFile(): StoredFileRef {
    return this.props.pdfFile;
  }
  get generatedAt(): Date {
    return this.props.generatedAt;
  }
  get generatedById(): string | null {
    return this.props.generatedById;
  }
  get sentAt(): Date | null {
    return this.props.sentAt;
  }

  isOwnedBy(clientId: string): boolean {
    return this.props.clientId === clientId;
  }

  /** Sending may be repeated (e.g. lost email): `sentAt` keeps the last delivery. */
  markSent(adminId: string, now: Date): void {
    this.props.sentAt = now;
    this.addDomainEvent(
      new ClientInvoiceSent(
        this.id,
        {
          invoiceNumber: this.props.invoiceNumber.value,
          clientId: this.props.clientId,
          actorId: adminId,
        },
        now,
      ),
    );
  }
}
